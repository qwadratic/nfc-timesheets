#!/bin/sh
# Push the `server`-tagged secrets from the local psst vault to /etc/nfc/env on the VM.
#
#   sh ops/sync-secrets.sh              # sync, restart, verify
#   sh ops/sync-secrets.sh --dry-run    # show which NAMES would be written, never values
#
# WHY THIS IS NOT `psst export`. `psst export --tag server` SILENTLY IGNORES `--tag` and
# exports the entire vault — verified 2026-08-12, it emitted ANDROID_KEYSTORE_PASSWORD and
# ADMIN_PASSWORD as well. Piping that into /etc/nfc/env would put the Play upload-key
# password on an internet-facing machine, where it protects the ability to ship an Android
# update to every worker. So this reads NAMES from `psst list --tag server` and fetches each
# value individually. If psst ever fixes the flag, this still works.
#
# WHY A WHOLE-FILE REWRITE. /etc/nfc/env is derived state; the vault is the source of truth.
# Appending would let a deleted secret live on forever, and the failure mode of a stale
# credential is worse than a missing one because it fails much later and much more quietly.
#
# The file never touches disk on this laptop and never appears in `ps`: values move over ssh
# stdin straight into `install`. Names are printed, values never are.
set -eu

HOST="${HOST:-timesheets.exe.xyz}"
ENV_PATH=/etc/nfc/env
SERVICE=nfc-api
DRY=0
[ "${1:-}" = "--dry-run" ] && DRY=1

cd "$(dirname "$0")/.."   # psst is project-scoped: outside the project it returns "Run: psst init"

# Only bullet lines: psst prints a "Secrets" heading and a "N secret(s)" footer, and a
# looser match happily turned the heading into a secret named "S".
names=$(psst list --tag server 2>/dev/null | grep '●' | sed -n 's/^[^A-Za-z]*\([A-Z][A-Z0-9_]*\).*/\1/p' | sort -u)
[ -n "$names" ] || { echo "sync-secrets: no secrets tagged 'server' — refusing to write an empty env"; exit 1; }

# The service will not boot without these, and an env file missing one is a broken machine
# rather than a partly-configured one. Fail here instead of after the restart.
for required in DATABASE_URL APP_KEY PORT; do
  echo "$names" | grep -qx "$required" || { echo "sync-secrets: $required is not in the vault under tag 'server' — refusing"; exit 1; }
done

echo "sync-secrets: $HOST$ENV_PATH"
for n in $names; do echo "  $n"; done

if [ "$DRY" = "1" ]; then echo "sync-secrets: dry run, nothing sent"; exit 0; fi

payload="# NFC TimeSheets backend environment
# GENERATED by ops/sync-secrets.sh from the psst vault (tag: server). Do not hand-edit:
# the next sync overwrites this file. Change the value in the vault and re-run instead.
"
for n in $names; do
  v=$(psst get "$n" 2>/dev/null) || { echo "sync-secrets: could not read $n"; exit 1; }
  case "$v" in ""|"Run: psst init"*) echo "sync-secrets: empty value for $n — refusing"; exit 1;; esac
  # No quoting: systemd EnvironmentFile treats quotes as literal characters.
  payload="$payload$n=$v
"
done

# Straight into place: 0640 root:app, so the deployer can write it and the service user can
# only read it. `install` is atomic, so a dropped connection cannot leave a half-written file
# that the service would then boot from.
printf '%s' "$payload" | ssh "$HOST" "sudo install -m 0640 -o root -g app /dev/stdin $ENV_PATH && sudo systemctl restart $SERVICE"

sleep 2
code=$(curl -s -o /dev/null -w '%{http_code}' "https://$HOST/health" || true)
if [ "$code" = "200" ]; then
  echo "sync-secrets: ok — $SERVICE restarted, /health $code"
else
  echo "sync-secrets: WROTE THE FILE BUT /health returned '$code'. Check: ssh $HOST journalctl -u $SERVICE -n 40"
  exit 1
fi
