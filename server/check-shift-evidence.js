export async function checkShiftEvidence({ call, owner, a, b, base, keepEvidence = false }) {
  for (const interval of [-1, 1, 59, 86401, 60.5, "60", null]) assert.throws(() => validatePolicy({location_interval_seconds:interval,proof_of_work_required:true}));
  for (const interval of [0,60,300,86400]) assert.equal(validatePolicy({location_interval_seconds:interval,proof_of_work_required:true}).location_interval_seconds, interval);
  for (const latitude of [91, -91, Infinity, "48"]) assert.throws(() => validateLocation({latitude,longitude:16,accuracy_m:2}));
  assert.throws(() => captureTime(new Date(Date.now()+60000).toISOString(), new Date(0)));
  assert.throws(() => decodePhoto("/9j/2Q=="));
  assert.throws(() => decodePhoto("not a jpeg"));
  const malformed = Buffer.alloc(200, 255); malformed[1]=216; malformed[199]=217;
  assert.throws(() => decodePhoto(malformed.toString("base64")), {code:"invalid_photo"});
  const excessiveDimensions=Buffer.from(photo,"base64");
  const frame=excessiveDimensions.indexOf(Buffer.from([255,192]));
  excessiveDimensions.writeUInt16BE(9000,frame+5);
  assert.throws(() => decodePhoto(excessiveDimensions.toString("base64")), {code:"invalid_photo"});
  assert.throws(() => decodePhoto(Buffer.alloc(2*1024*1024+1).toString("base64")),{code:"invalid_photo"});
  assert.ok(decodePhoto(photo).length > 128);
  const policy = {location_interval_seconds:60,proof_of_work_required:true};
  const set = (body, cookie=a.cookie) => call("/admin/shift-policy", {cookie,method:"PUT",body});
  assert.equal((await set(policy, a.workerCookie)).status,401);
  assert.equal((await set({...policy,location_interval_seconds:10})).status,422);
  assert.equal((await set(policy)).status,200);
  assert.deepEqual((await call("/shift-policy", {cookie:a.workerCookie})).data.policy,policy);
  assert.deepEqual((await call("/shift-policy", {cookie:b.workerCookie})).data.policy,{location_interval_seconds:0,proof_of_work_required:false});
  const uuid=randomUUID();
  const start=new Date(Date.now()-300000).toISOString();
  const opened=await call("/shifts/open", {cookie:a.workerCookie,body:{client_uuid:uuid,location_uuid:a.zone.id,start_time:start}});
  assert.equal(opened.status,201,JSON.stringify(opened));
  assert.equal(opened.data.shift.proof_of_work_required,true);
  assert.equal(opened.data.shift.location_interval_seconds,60);
  const workerCall=(path,body,cookie=a.workerCookie)=>call(`/shifts/${uuid}/${path}`,{cookie,body});
  const close=(extra={})=>call("/shifts/close",{cookie:a.workerCookie,body:{client_uuid:uuid,end_time:new Date().toISOString(),...extra}});
  assert.equal((await close()).data.error,"proof_required");
  assert.equal((await close({auto_closed:true})).data.error,"proof_required");
  assert.equal((await close({manual:true})).data.error,"proof_required");
  const sample={sample_uuid:randomUUID(),captured_at:new Date(Date.now()-1000).toISOString(),latitude:48.2,longitude:16.3,accuracy_m:4};
  assert.equal((await workerCall("locations",sample,b.workerCookie)).status,404);
  assert.equal((await workerCall("locations",{...sample,latitude:91})).status,422);
  assert.equal((await workerCall("locations",{...sample,captured_at:new Date(Date.now()+60000).toISOString()})).status,422);
  assert.equal((await workerCall("locations",sample)).status,201);
  assert.equal((await workerCall("locations",sample)).status,200);
  assert.equal((await workerCall("locations",{...sample,sample_uuid:randomUUID()})).status,429);
  assert.equal((await workerCall("proof-challenge",{},b.workerCookie)).status,404);
  const challenge=await workerCall("proof-challenge",{});
  assert.equal(challenge.status,201);
  await owner.query("UPDATE shifts SET proof_challenged_at=now()-interval '11 minutes' WHERE id=$1",[opened.data.shift.id]);
  assert.equal((await workerCall("proof",{challenge_id:challenge.data.challenge_id,captured_at:new Date().toISOString(),jpeg_base64:photo})).data.error,"proof_challenge_expired");
  await owner.query("UPDATE shifts SET proof_challenged_at=now() WHERE id=$1",[opened.data.shift.id]);
  const captured=new Date().toISOString();
  const oversized=await new Promise((resolve,reject)=>{
    const req=request(`${base}/shifts/${uuid}/proof`,{method:"POST",headers:{cookie:a.workerCookie,"x-app-key":process.env.APP_KEY,"content-type":"application/json","content-length":"2801000",connection:"close"}},res=>{res.resume();res.on("end",()=>resolve(res.statusCode));});
    req.on("error",reject); req.end();
  });
  assert.equal(oversized,413);
  assert.equal((await workerCall("proof",{challenge_id:challenge.data.challenge_id,captured_at:captured,jpeg_base64:"x"})).status,422);
  const upload={challenge_id:challenge.data.challenge_id,captured_at:captured,jpeg_base64:photo};
  const uploaded=await workerCall("proof",upload);
  assert.equal(uploaded.status,201,JSON.stringify(uploaded));
  assert.equal((await workerCall("proof",upload)).data.proof_id,uploaded.data.proof_id);
  assert.equal((await close({proof_id:randomUUID()})).data.error,"proof_required");
  assert.equal((await close({proof_id:"-".repeat(36)})).data.error,"proof_required");
  await owner.query("UPDATE shift_proofs SET captured_at=now()-interval '11 minutes' WHERE id=$1",[uploaded.data.proof_id]);
  assert.equal((await close({proof_id:uploaded.data.proof_id})).data.error,"proof_expired");
  await owner.query("UPDATE shift_proofs SET captured_at=now() WHERE id=$1",[uploaded.data.proof_id]);
  // A policy edit cannot remove the requirement from a running shift.
  assert.equal((await set({location_interval_seconds:0,proof_of_work_required:false})).status,200);
  assert.equal((await close()).data.error,"proof_required");
  const closed=await close({proof_id:uploaded.data.proof_id});
  assert.equal(closed.status,200,JSON.stringify(closed));
  assert.equal(closed.data.shift.proof_id,uploaded.data.proof_id);
  assert.equal((await close()).status,200,"idempotent completed close needs no new photo");
  assert.equal((await workerCall("locations",{...sample,sample_uuid:randomUUID()})).status,409);
  assert.equal((await workerCall("proof-challenge",{})).status,409);
  const endpoint=`/admin/shifts/${uuid}/evidence`;
  assert.equal((await call(endpoint,{cookie:b.cookie})).status,404);
  assert.equal((await call(endpoint,{cookie:a.workerCookie})).status,401);
  const evidence=await call(endpoint,{cookie:a.cookie});
  assert.equal(evidence.data.samples.length,1);
  assert.equal(evidence.data.proof.id,uploaded.data.proof_id);
  const photoPath=`${base}/admin/shifts/${uuid}/proof/${uploaded.data.proof_id}`;
  const image=await fetch(photoPath,{headers:{cookie:a.cookie}});
  assert.equal(image.status,200);
  assert.equal(image.headers.get("content-type"),"image/jpeg");
  assert.equal(image.headers.get("cache-control"),"no-store");
  assert.deepEqual(Buffer.from(await image.arrayBuffer()),Buffer.from(photo,"base64"));
  assert.equal((await fetch(photoPath,{headers:{cookie:b.cookie}})).status,404);
  // Server timeout must not require a photo, but later human resolution must.
  await owner.query("UPDATE shifts SET auto_closed=true,corrected_at=NULL,proof_id=NULL WHERE id=$1",[opened.data.shift.id]);
  const resolve=body=>call(`/shifts/${opened.data.shift.id}/resolve`,{cookie:a.workerCookie,body:{end_time:new Date().toISOString(),...body}});
  assert.equal((await resolve({})).data.error,"proof_required");
  const resolutionChallenge=await workerCall("proof-challenge",{});
  const resolutionPhoto=await workerCall("proof",{challenge_id:resolutionChallenge.data.challenge_id,captured_at:new Date().toISOString(),jpeg_base64:photo});
  assert.equal((await resolve({proof_id:resolutionPhoto.data.proof_id})).status,200);
  const {query,withWorkspace}=await import("./lib/db.js");
  await assert.rejects(withWorkspace(b.id,()=>query("INSERT INTO shift_locations(sample_uuid,shift_id,captured_at,latitude,longitude,accuracy_m) VALUES($1,$2,now(),0,0,1)",[randomUUID(),opened.data.shift.id])),{code:"23503"});
  if (!keepEvidence) await owner.query("DELETE FROM shifts WHERE id=$1",[opened.data.shift.id]);
  else {
    await set(policy);
    const active = randomUUID();
    assert.equal((await call("/shifts/open",{cookie:a.workerCookie,body:{client_uuid:active,location_uuid:a.zone.id,start_time:new Date().toISOString()}})).status,201);
    console.log(`EVIDENCE_PREVIEW closed=${uuid} active=${active}`);
  }
  console.log("check-shift-evidence: PASS (policy snapshots, proof close/resolve gate, freshness, location cadence, own-worker scope, tenant RLS/FK and private JPEG)");
}
